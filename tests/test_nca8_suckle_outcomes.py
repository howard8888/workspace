def test_partial_task_forecast_is_not_mistaken_for_a_changed_local_goal():
    """Explicit contract fixture: a short forecast can coexist with the unchanged farther target.

    This tests relation semantics, not live selection of an early four-tick H
    application. The live H operation uses a shorter horizon only at its task tail.
    """
    from nca8_suckle_outcomes import _compare
    _, first, _, intervals = buffered()
    original = first.suckle_correspondence.registration
    preview = replace(original.preview, predicted_closure=0.4, horizon_ticks=4)
    request = replace(original.request, lease_ticks=4)
    target = replace(original.targets[0], target=replace(original.targets[0].target, lease_ticks=4))
    claim = replace(original, preview=preview, request=request, targets=(target,))
    assert claim.authorization_status == "authorized" and claim.preview.predicted_closure == 0.4
    assert claim.targets[0].target.endpoint == claim.request.desired_closure == 0.6
    item = next(i for i in intervals if any(f.event_tick == 4 for f in i.deliveries))
    endpoint = item.endpoints()[0]
    relations, _, _ = _compare(claim, endpoint)
    assert dict(relations)["seal"] == "not_predicted" and dict(relations)["closure"] == "matched"
