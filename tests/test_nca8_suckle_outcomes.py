def prepared(case="nominal"):
    trial = create_suckle_trial_v1(case, outcomes_enabled=True)
    first = trial.focal_step()
    return trial, first, trial.core.suckle_outcomes


def buffered(ticks=12, case="nominal"):
    trial, first, owner = prepared(case)
    for _ in range(ticks):
        trial.advance_lower()
    return trial, first, owner, tuple(trial._suckle_intervals)


def snapshot(owner):
    return (tuple(x.as_dict() for x in owner.pending()), tuple(x.as_dict() for x in owner.history()), owner.retained_counts(),
            owner._last_cutoff, owner._last_interval, owner._last_command_id, owner._execution_end_tick,
            tuple((x.installed, x.command_intervals, x.ended_tick, x.end_reason) for x in owner._pending.values()))


def endpoint_fixture(intervals, transform):
    """Alter only the original event8 acquisition, not its prediction or controller."""
    result = []
    for item in intervals:
        deliveries, observations = [], []
        for sample in item.deliveries:
            visual = next((obs for obs in item.observations if obs.sample_id == sample.sample_id), None)
            if sample.event_tick == 8:
                sample, visual = transform(sample, visual)
            if sample is not None:
                deliveries.append(sample)
            if visual is not None:
                observations.append(visual)
        result.append(replace(item, deliveries=tuple(deliveries), observations=tuple(observations)))
    return tuple(result)


