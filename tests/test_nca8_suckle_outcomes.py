@pytest.mark.parametrize("kind", ["order", "duplicate", "gap", "future", "foreign", "conflict", "copied_target", "foreign_command"])
def test_invalid_batch_cannot_partially_consume_exposure_or_evidence(kind):
    _, _, owner, intervals = buffered()
    batch, cutoff = list(intervals), 12
    if kind == "order":
        batch[0], batch[1] = batch[1], batch[0]
    elif kind == "duplicate":
        batch.insert(1, batch[0])
    elif kind == "gap":
        batch.pop(0)
    elif kind == "future":
        cutoff = 11
    elif kind == "foreign":
        batch[-1] = replace(batch[-1], deliveries=(replace(batch[-1].deliveries[0], stream=MotorStreamRefV1("foreign", 2)),), observations=())
    elif kind == "conflict":
        sample = replace(batch[2].deliveries[0], sample_id=batch[1].deliveries[0].sample_id)
        batch[2] = replace(batch[2], deliveries=(sample,), observations=(replace(batch[2].observations[0], sample_id=sample.sample_id),))
    elif kind == "copied_target":
        report = batch[0].reports[0]
        batch[0] = replace(batch[0], reports=(replace(report, committed_target=replace(report.committed_target)),))
    else:
        batch[0] = replace(batch[0], command=replace(batch[0].command, stream=MotorStreamRefV1("foreign", 2)))
    before = snapshot(owner)
    with pytest.raises((ValueError, TypeError)):
        owner.consume_intervals(tuple(batch), cutoff_tick=cutoff)
    assert snapshot(owner) == before


